"""Answer-level comparison of the saved predictions (no model calls).

Writes tables/analysis_numbers.tex (macros) and tables/type_table.tex for the report.
"""
import json
import statistics as st
from pathlib import Path

BS = "\\"


def _load(path):
    p = Path(path)
    if not p.exists():
        return {}
    return {r["id"]: r for r in (json.loads(x) for x in p.read_text(encoding="utf-8").splitlines() if x.strip())}


def words(r):
    return len(r["pred"].split())


def complete(r):
    return set(r["gold_ids"]) <= set(r["selected_ids"])


def f(x, d=3):
    return f"{x:.{d}f}"


def write(ra):
    R = Path(ra.RESULTS)
    b, m, g = _load(R / "baseline" / "test_predictions.jsonl"), _load(R / "mipro" / "test_predictions.jsonl"), \
        _load(R / ra.GEPA / "test_predictions.jsonl")
    if not (b and g):
        return
    ids = [i for i in b if i in g]
    M = {}
    better = [i for i in ids if g[i]["f1"] > b[i]["f1"] + 1e-9]
    worse = [i for i in ids if g[i]["f1"] < b[i]["f1"] - 1e-9]
    M["GBetter"], M["GWorse"] = len(better), len(worse)
    M["GSame"] = len(ids) - len(better) - len(worse)
    M["SelSame"] = sum(g[i]["selected_ids"] == b[i]["selected_ids"] for i in ids)
    M["BaseLong"] = sum(words(b[i]) > 5 for i in ids)
    M["GepaLong"] = sum(words(g[i]) > 5 for i in ids)
    M["BaseWords"] = f(st.mean(words(b[i]) for i in ids), 2)
    M["GepaWords"] = f(st.mean(words(g[i]) for i in ids), 2)
    M["ImpLong"] = sum(words(b[i]) > 5 for i in better)
    M["ImpComplete"] = sum(complete(b[i]) for i in better)
    M["WorLong"] = sum(words(g[i]) > 5 for i in worse)
    M["WorComplete"] = sum(complete(b[i]) for i in worse)
    if m:
        M["MiproLong"] = sum(words(m[i]) > 5 for i in ids if i in m)
        M["MiproWords"] = f(st.mean(words(m[i]) for i in ids if i in m), 2)
    yn = [i for i in ids if b[i]["gold"].strip().lower() in ("yes", "no")]
    M["YNn"] = len(yn)
    M["YNBase"] = f(st.mean(b[i]["f1"] for i in yn))
    M["YNGepa"] = f(st.mean(g[i]["f1"] for i in yn))
    if m:
        M["YNMipro"] = f(st.mean(m[i]["f1"] for i in yn))
    rest = [i for i in ids if i not in yn]
    M["RestN"] = len(rest)
    M["RestBase"] = f(st.mean(b[i]["f1"] for i in rest))
    M["RestGepa"] = f(st.mean(g[i]["f1"] for i in rest))
    if m:
        M["RestMipro"] = f(st.mean(m[i]["f1"] for i in rest))
    # by HotpotQA question type
    rows = []
    for t in sorted({b[i]["type"] for i in ids}):
        s = [i for i in ids if b[i]["type"] == t]
        row = [t, str(len(s)), f(st.mean(b[i]["f1"] for i in s)),
               f(st.mean(m[i]["f1"] for i in s)) if m else "n/a", f(st.mean(g[i]["f1"] for i in s))]
        rows.append(row)
        key = t.capitalize()
        M[key + "N"], M[key + "Base"], M[key + "Mipro"], M[key + "Gepa"] = row[1], row[2], row[3], row[4]
    tab = [BS + "begin{tabular}{lrrrr}", BS + "hline",
           "Question type & Questions & Baseline & MIPROv2 & GEPA " + BS + BS + " " + BS + "hline"]
    tab += [" & ".join(r) + " " + BS + BS for r in rows] + [BS + "hline", BS + "end{tabular}"]
    (ra.OUT / "type_table.tex").write_text("\n".join(tab) + "\n", encoding="utf-8")
    lines = ["% generated by src/analysis.py"] + [BS + "newcommand{" + BS + k + "}{" + str(v) + "}" for k, v in sorted(M.items())]
    (ra.OUT / "analysis_numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
